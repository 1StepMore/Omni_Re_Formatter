#!/usr/bin/env python3
"""doc_inventory — ORF 文档真值门禁（issue ORF#73）。

从源码派生「活体数字」（MCP 工具数、MD 输出格式数、XLIFF 回填格式数、
场景数、版本），与 README/AGENTS/docs 中的声明比对；生成
docs/dev/doc-inventory.md 行集，并做引用路径完整性检查。

用法：
    python scripts/doc_inventory.py            # 生成 docs/dev/doc-inventory.md
    python scripts/doc_inventory.py --check    # 校验：exit 0 = 干净，1 = 漂移

与套件仓 / OPP / OL 的 doc_inventory 同源同思想（右尺寸版）；纯标准库。
注意：ORF 的 MCP 配置是 fail-CLOSED（导入 orf.mcp.* 需要 allowlist 环境变
量），派生函数在导入前 setdefault 一个惰性占位值——审计只读注册表，
allowlist 值本身不参与任何路径检查。
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

AUTO_HEADER = "<!-- AUTO-GENERATED by scripts/doc_inventory.py — do not edit by hand. -->"
INVENTORY_PATH = ROOT / "docs" / "dev" / "doc-inventory.md"

# ── 派生源（活体） ──────────────────────────────────────────────────────────


def _derive_tools() -> tuple[int, list[str]]:
    """MCP 工具：orf.mcp.server 的 _TOOL_DISPATCH 是唯一权威。

    fail-CLOSED：orf.mcp.config 在导入时要求 allowlist 环境变量；本脚本
    只读注册表，setdefault 一个占位值即可（不覆盖调用方已设的值）。
    """
    os.environ.setdefault("MCP_ALLOWED_DIRECTORIES", "/tmp")
    from orf.mcp.server import _TOOL_DISPATCH

    names = sorted(_TOOL_DISPATCH)
    return len(names), names


def _derive_md_outputs() -> tuple[int, list[str]]:
    from orf.mcp.tools.get_capabilities import _MD_OUTPUT_FORMATS

    return len(_MD_OUTPUT_FORMATS), list(_MD_OUTPUT_FORMATS)


def _derive_xliff_backfills() -> tuple[int, list[str]]:
    from orf.mcp.tools.get_capabilities import _XLIFF_BACKFILL_FORMATS

    return len(_XLIFF_BACKFILL_FORMATS), list(_XLIFF_BACKFILL_FORMATS)


def _derive_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data["project"]["version"])


def _derive_scenarios() -> tuple[int, dict[str, int]]:
    """scenarios/**/*.yaml 计数 + tier 拆分（跳 dot 目录，缺省 tier 1）。"""
    scenarios = ROOT / "scenarios"
    if not scenarios.is_dir():
        return 0, {}
    yamls = sorted(
        p
        for p in scenarios.rglob("*.yaml")
        if p.is_file() and not any(part.startswith(".") for part in p.parts)
    )
    tiers: dict[str, int] = {}
    for p in yamls:
        tier = "1"
        for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if re.match(r"tier\s*:", line.strip()):
                tier = line.split(":", 1)[1].strip()
                break
        tiers[tier] = tiers.get(tier, 0) + 1
    return len(yamls), tiers


# ── 声明点 ──────────────────────────────────────────────────────────────────

_TOOL_COUNT = lambda: _derive_tools()[0]  # noqa: E731
_MD_COUNT = lambda: _derive_md_outputs()[0]
_XLIFF_COUNT = lambda: _derive_xliff_backfills()[0]
_SCENARIO_COUNT = lambda: _derive_scenarios()[0]

_CLAIM_SITES: tuple[tuple[str, re.Pattern[str], int, object], ...] = (
    ("README.md", re.compile(r"(\d+) MCP tools"), 1, _TOOL_COUNT),
    ("AGENTS.md", re.compile(r"MCP tools \((\d+) total\)"), 1, _TOOL_COUNT),
    ("AGENTS.md", re.compile(r"(\d+) output formats"), 1, _MD_COUNT),
    ("README.md", re.compile(r"(\d+) output formats"), 1, _MD_COUNT),
    ("AGENTS.md", re.compile(r"(\d+) backfill formats"), 1, _XLIFF_COUNT),
    ("README.md", re.compile(r"(\d+) backfill formats"), 1, _XLIFF_COUNT),
    ("README.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
    ("AGENTS.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
)

REFERENTIAL_SCOPE = ("README.md", "AGENTS.md", "docs/API.md")
_PATH_TOKEN_RE = re.compile(r"`([^`\n]+)`")
_PATH_SUFFIXES = (
    ".md", ".py", ".yaml", ".yml", ".toml", ".sh", ".json", ".txt",
)
_PATH_ANCHORS = (
    "tests/", "docs/", "scripts/", "src/", "scenarios/",
    "README.md", "AGENTS.md", "CHANGELOG.md", "CONTRIBUTING.md",
    "pyproject.toml", ".pre-commit-config.yaml",
)


# ── BEGIN SHARED CROSS-REPO RESOLUTION (e2e-test-suite#253) ──────────────────
# Byte-identical in Omni_Localizer / Omni_Pre_Processor / Omni_Re_Formatter.
# Edit all three together; tests/test_doc_inventory_copy_parity.py in the
# suite repo fails when the copies drift.
#
# A backticked path with no repo prefix is a path in THIS repo and must
# exist. A prefixed token -- ``suite:docs/dev/x.md``, ``ol:src/ol_md/y.py``,
# ``opp:src/opp/z.py``, ``orf:tests/w.py`` -- names the owning repo. A
# prefixed token is verifiable only when that checkout is present; without
# it the reference is counted as skipped (never silently treated as valid)
# and the final message says so.

_CROSS_REPO_MARKERS: dict[str, tuple[str, ...]] = {
    "suite": ("omni_suite", "omni_mcp"),
    "opp": ("src/opp",),
    "ol": ("src/ol_md",),
    "orf": ("src/orf",),
}
_CROSS_REPO_DIRNAMES: dict[str, tuple[str, ...]] = {
    "suite": ("", "e2e-test-suite", "suite"),
    "opp": ("Omni_Pre_Processor",),
    "ol": ("Omni_Localizer",),
    "orf": ("Omni_Re_Formatter",),
}
_CROSS_REPO_PREFIXES = tuple(sorted(_CROSS_REPO_MARKERS))
_SKIP_PREFIXES = ("http://", "https://", "/", "~", "pip ", "python ", "uv ")


def _split_repo_prefix(token: str) -> tuple[str | None, str]:
    """``suite:docs/x.md`` -> ``("suite", "docs/x.md")``; unprefixed is local."""
    for repo in _CROSS_REPO_PREFIXES:
        head = repo + ":"
        if token.startswith(head):
            return repo, token[len(head):]
    return None, token


def _looks_like_repo_path(token: str) -> bool:
    """反引号 token 是否像仓库相对路径（可有跨仓前缀，以顶层锚点开头）。

    类名、产物名（zip 内部文件 / OOXML 布局）、裸后缀（``.md``）都不满足，
    避免误报。
    """
    _, path = _split_repo_prefix(token)
    if not path.startswith(_PATH_ANCHORS):
        return False
    base = path.rsplit("/", 1)[-1]
    if not base.split(".")[0]:
        return False  # 裸后缀：最后一个点前没有 stem，不是路径
    return not any(c in path for c in '*{}<> "\\')


def _env_cross_roots(root: Path) -> list[Path]:
    """Candidate checkouts, highest priority first.

    ``DOC_CROSS_ROOT`` (``os.pathsep``-separated) wins so CI can point at the
    sibling checkout explicitly; then the conventional layouts -- a sibling of
    this repo, ``../e2e-test-suite``, ``../suite``.
    """
    bases: list[Path] = []
    for part in os.environ.get("DOC_CROSS_ROOT", "").split(os.pathsep):
        part = part.strip()
        if part and Path(part) not in bases:
            bases.append(Path(part))
    for base in (root.parent, root.parent / "e2e-test-suite", root.parent / "suite"):
        if base not in bases:
            bases.append(base)
    return bases


def _is_checkout(repo: str, path: Path) -> bool:
    return path.is_dir() and any((path / marker).exists()
                                 for marker in _CROSS_REPO_MARKERS[repo])


def _resolve_cross_roots(root: Path) -> dict[str, Path]:
    """Resolve every known repo to a real checkout, including this one.

    Absent repos are left out of the mapping -- a single-repo CI checkout
    legitimately cannot verify them, so their references are reported as
    skipped rather than passed or failed.
    """
    resolved: dict[str, Path] = {}
    for repo, markers in _CROSS_REPO_MARKERS.items():
        if any((root / marker).exists() for marker in markers):
            resolved[repo] = root
            break
    for repo, dirnames in _CROSS_REPO_DIRNAMES.items():
        if repo in resolved:
            continue
        for base in _env_cross_roots(root):
            for dirname in dirnames:
                cand = base / dirname if dirname else base
                if _is_checkout(repo, cand):
                    resolved[repo] = cand
                    break
            if repo in resolved:
                break
    return resolved


def _check_referential_paths(failures: list[str]) -> dict[str, int]:
    """Backticked paths: local ones must exist; prefixed ones need their repo.

    Returns the per-repo count of prefixed references that could not be
    verified because that checkout is absent (``{"ol": 2}`` etc.).
    """
    roots = _resolve_cross_roots(ROOT)
    skipped: dict[str, int] = {}
    for rel in REFERENTIAL_SCOPE:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in _PATH_TOKEN_RE.finditer(text):
            token = m.group(1).strip()
            if not token or token.startswith(_SKIP_PREFIXES):
                continue
            repo, raw_path = _split_repo_prefix(token)
            if not _looks_like_repo_path(token):
                continue
            target = raw_path.split(":", 1)[0]  # ``path.py:62`` / ``path.py::test``
            if not target:
                continue
            if repo is None:
                if not (ROOT / target).exists():
                    failures.append(
                        f"{rel}: backticked path does not exist: {token!r} "
                        "(this repo)"
                    )
                continue
            base = roots.get(repo)
            if base is None:
                skipped[repo] = skipped.get(repo, 0) + 1
                continue
            if not (base / target).exists():
                failures.append(
                    f"{rel}: backticked path does not exist: {token!r} "
                    f"(repo {repo!r} resolved at {base})"
                )
    return skipped
# ── END SHARED CROSS-REPO RESOLUTION (e2e-test-suite#253) ────────────────────


def _check_claims(failures: list[str]) -> None:
    for rel, pattern, group, derive in _CLAIM_SITES:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        expected = derive()  # type: ignore[operator]
        for m in pattern.finditer(text):
            claimed = int(m.group(group))
            if claimed != expected:
                failures.append(
                    f"{rel}: claims {m.group(0)!r} but the source derives "
                    f"{expected} — update the doc when the surface changes"
                )


# ── 行集生成 ────────────────────────────────────────────────────────────────


def _doc_rows() -> list[tuple[str, int]]:
    """行集键必须是 ROOT **相对**路径（绝对路径会让新鲜度比较在任何不同
    checkout 位置上必然失败）。"""
    rows = []
    for p in sorted((ROOT / "docs").rglob("*.md")):
        if "dev/doc-inventory" in p.as_posix():
            continue
        rows.append((p.relative_to(ROOT).as_posix(),
                     len(p.read_text(encoding="utf-8", errors="replace").splitlines())))
    for rel in ("README.md", "AGENTS.md"):
        p = ROOT / rel
        if p.is_file():
            rows.append((rel, len(p.read_text(encoding="utf-8", errors="replace").splitlines())))
    rows.sort()
    return rows


def generate() -> str:
    tools, tool_names = _derive_tools()
    md_outs, _md_names = _derive_md_outputs()
    xliff_backs, _xliff_names = _derive_xliff_backfills()
    version = _derive_version()
    scenarios, tiers = _derive_scenarios()

    lines = [
        AUTO_HEADER,
        "",
        "# ORF doc inventory",
        "",
        "- Generated by `scripts/doc_inventory.py`; verify with `--check`.",
        f"- Source-derived: version **{version}** · MCP tools **{tools}** "
        f"({', '.join(tool_names)}) · MD output formats **{md_outs}** · "
        f"XLIFF backfill formats **{xliff_backs}** · scenarios **{scenarios}** "
        f"(tiers={dict(sorted(tiers.items()))})",
        "",
        "| Document | Lines |",
        "|---|---:|",
    ]
    lines += [f"| {rel} | {n} |" for rel, n in _doc_rows()]
    lines.append("")
    return "\n".join(lines)


def check() -> int:
    failures: list[str] = []
    _check_claims(failures)
    skipped = _check_referential_paths(failures)

    if INVENTORY_PATH.is_file():
        if INVENTORY_PATH.read_text(encoding="utf-8") != generate():
            failures.append(
                "docs/dev/doc-inventory.md is stale — run "
                "`python scripts/doc_inventory.py` to regenerate"
            )
    else:
        failures.append("docs/dev/doc-inventory.md missing — run scripts/doc_inventory.py")

    if failures:
        print("check FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    if skipped:
        detail = ", ".join(f"{repo}: {n}" for repo, n in sorted(skipped.items()))
        total = sum(skipped.values())
        print(
            "check passed: claims match source-derived values, local paths "
            f"resolve, inventory fresh; {total} cross-repo reference(s) NOT "
            f"verified ({detail}) — no checkout for those repos. "
            "Set DOC_CROSS_ROOT to verify them."
        )
        return 0
    print("check passed: claims match source-derived values, paths resolve, inventory fresh.")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="doc_inventory")
    ap.add_argument("--check", action="store_true", help="verify instead of generate")
    args = ap.parse_args(argv)
    if args.check:
        return check()
    INVENTORY_PATH.parent.mkdir(parents=True, exist_ok=True)
    INVENTORY_PATH.write_text(generate(), encoding="utf-8")
    print(f"Wrote {INVENTORY_PATH} ({len(_doc_rows())} rows).")
    print("Regenerate after doc changes; verify with --check (exit 0 = clean).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
